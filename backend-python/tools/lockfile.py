"""Turn `pip install --dry-run --report` output into a requirements file with hashes.

Run inside the build image by tools/relock.sh; prints the lockfile to stdout.
"""

import json
import sys

HEADER = """# Generated by tools/relock.sh — do not edit. The declared ranges live in pyproject.toml.
#
# Installed with --require-hashes, which is why every transitive dependency appears here and why
# each line carries its sha256: a substituted or tampered dist fails the build rather than shipping.
# Adding a dependency means editing pyproject.toml and re-running that script, not appending here.
#
# One line per package, pinned and hashed."""


def main(report_path: str) -> int:
    with open(report_path, encoding="utf-8") as handle:
        report = json.load(handle)

    if report.get("version") != "1":
        print(f"unexpected report version {report.get('version')!r}", file=sys.stderr)
        return 1

    lines: list[str] = []
    for item in report["install"]:
        name = item["metadata"]["name"]
        # The project itself: a local directory, so there is no released version to pin and no
        # published artefact to hash.
        if item.get("is_direct"):
            continue
        hashes = item.get("download_info", {}).get("archive_info", {}).get("hashes", {})
        digest = hashes.get("sha256")
        if not digest:
            # Refuse rather than emit a line --require-hashes would reject at build time, where the
            # failure would be a puzzle instead of this sentence.
            print(f"no sha256 for {name}; cannot lock", file=sys.stderr)
            return 1
        lines.append(f"{name}=={item['metadata']['version']} --hash=sha256:{digest}")

    if not lines:
        print("the report installs nothing", file=sys.stderr)
        return 1

    print(HEADER)
    for line in sorted(lines, key=str.lower):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
